-- Location dimension (ADR-0009, ADR-0018). Type 1: loads overwrite changed values, but
-- never with data older than what is stored (source_updated_at guard, ADR-0014).
CREATE TABLE warehouse.dim_location (
    location_key      integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_code     text        NOT NULL UNIQUE,
    location_name     text        NOT NULL,
    country           text        NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
    source_updated_at timestamptz NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT dim_location_code_format
        CHECK (location_code ~ '^[A-Z]{2}-[0-9]{2}$' OR location_key = -1)
);

COMMENT ON TABLE warehouse.dim_location IS
    'Grain: one row per stock location. Business key: location_code. Key -1 is the unknown member.';

-- Unknown member (ADR-0009): facts never have a NULL location.
INSERT INTO warehouse.dim_location
    (location_key, location_code, location_name, country, source_updated_at)
VALUES (-1, 'UNKNOWN', 'Unknown location', 'ZZ', '1970-01-01 00:00:00+00');
