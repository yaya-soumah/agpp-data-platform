-- Product dimension (ADR-0009, ADR-0010). Type 1: a price change overwrites the row.
CREATE TABLE warehouse.dim_product (
    product_key        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         text          NOT NULL UNIQUE,
    supplier_key       integer       NOT NULL REFERENCES warehouse.dim_supplier (supplier_key),
    supplier_sku       text          NOT NULL,
    product_name       text          NOT NULL,
    category           text          NOT NULL,
    unit_price         numeric(12, 4) NOT NULL,
    currency           text          NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    min_order_quantity integer       NOT NULL CHECK (min_order_quantity >= 1),
    lead_time_days     integer       NOT NULL CHECK (lead_time_days BETWEEN 0 AND 365),
    is_active          boolean       NOT NULL,
    source_updated_at  timestamptz   NOT NULL,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT dim_product_supplier_sku_key UNIQUE (supplier_key, supplier_sku),
    CONSTRAINT dim_product_price_positive CHECK (unit_price > 0 OR product_key = -1)
);

COMMENT ON TABLE warehouse.dim_product IS
    'Grain: one row per supplier product. Business key: product_id (supplier_id:supplier_sku). '
    'Key -1 is the unknown member.';

