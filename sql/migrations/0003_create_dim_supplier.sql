-- Supplier dimension (ADR-0009, ADR-0010). Type 1: loads overwrite changed values.
CREATE TABLE warehouse.dim_supplier (
    supplier_key  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id   text        NOT NULL UNIQUE,
    supplier_name text        NOT NULL,
    country       text        NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE warehouse.dim_supplier IS
    'Grain: one row per supplier. Business key: supplier_id. Key -1 is the unknown member.';

-- Unknown member (ADR-0009): facts never have a NULL supplier.
INSERT INTO warehouse.dim_supplier (supplier_key, supplier_id, supplier_name, country)
VALUES (-1, 'UNKNOWN', 'Unknown supplier', 'ZZ');
