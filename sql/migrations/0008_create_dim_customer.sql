-- Customer dimension (ADR-0009, ADR-0016). Type 1: loads overwrite changed values, but
-- never with data older than what is stored (source_updated_at guard, ADR-0014).
CREATE TABLE warehouse.dim_customer (
    customer_key      integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       text        NOT NULL UNIQUE,
    customer_name     text        NOT NULL,
    country           text        NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
    source_updated_at timestamptz NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE warehouse.dim_customer IS
    'Grain: one row per customer. Business key: customer_id. Key -1 is the unknown member.';

-- Unknown member (ADR-0009): facts never have a NULL customer.
INSERT INTO warehouse.dim_customer
    (customer_key, customer_id, customer_name, country, source_updated_at)
VALUES (-1, 'UNKNOWN', 'Unknown customer', 'ZZ', '1970-01-01 00:00:00+00');
